namespace Portfolio.ApiBase.Configuration;

/// <summary>
/// Configures Kestrel HTTPS, loading certificates from PEM files (.pem + .key).
/// </summary>
/// <remarks>
/// In development, if no certificate is found, it attempts to use the .NET default developer certificate.
/// </remarks>
public static partial class HttpsConfigurator
{
    // Env vars constants (overrides)
    public const string ENV_CERTIFICATE_PEM_PATH = "HTTPS_CERTIFICATE_PEM_PATH";
    public const string ENV_CERTIFICATE_KEY_PATH = "HTTPS_CERTIFICATE_KEY_PATH";
    public const string ENV_SSL_PROTOCOLS = "HTTPS_SSL_PROTOCOLS";
    public const string ENV_CLIENT_CERT_MODE = "HTTPS_CLIENT_CERT_MODE";

    /// <summary>
    /// Loads HTTPS configurations from appsettings.json and overrides them with env vars.
    /// </summary>
    private static HttpsSettings LoadHttpsSettings(IConfiguration configuration, ILogger logger)
    {
        var settings = configuration.GetSection("Https").Get<HttpsSettings>() ?? new HttpsSettings();
        configuration.GetSection("Https").Bind(settings);

        // Sobrescreve com env vars
        string? val;

        val = configuration[ENV_CERTIFICATE_PEM_PATH];
        if (!string.IsNullOrEmpty(val))
        {
            settings = settings with { CertificatePemPath = val };
            LogCertificatePemPathOverridden(logger, val);
        }

        val = configuration[ENV_CERTIFICATE_KEY_PATH];
        if (!string.IsNullOrEmpty(val))
        {
            settings = settings with { CertificateKeyPath = val };
            LogCertificateKeyPathOverridden(logger, val);
        }

        val = configuration[ENV_SSL_PROTOCOLS];
        if (!string.IsNullOrEmpty(val))
        {
            settings = settings with { SslProtocols = val.Split([';', ','], StringSplitOptions.RemoveEmptyEntries) };
            LogSslProtocolsOverridden(logger, val);
        }

        val = configuration[ENV_CLIENT_CERT_MODE];
        if (!string.IsNullOrEmpty(val))
        {
            settings = settings with { ClientCertificateMode = val };
            LogClientCertificateModeOverridden(logger, val);
        }

        return settings;
    }

    /// <summary>
    /// Loads the X509 certificate from the configurations (PEM).
    /// If not found, falls back to the .NET developer certificate.
    /// </summary>
    private static X509Certificate2? LoadCertificate(HttpsSettings settings, ILogger logger)
    {
        // 1. Try loading from the configured PE
        if (!string.IsNullOrEmpty(settings.CertificatePemPath))
        {
            try
            {
                string? keyPath = settings.CertificateKeyPath;
                if (string.IsNullOrEmpty(keyPath))
                {
                    // Fallback: Try to find a .key file with the same name
                    keyPath = Path.ChangeExtension(settings.CertificatePemPath, ".key");
                    LogCertificateKeyPathFallback(logger, keyPath);
                }

                LogLoadingPemCertificate(logger, settings.CertificatePemPath, keyPath);

                var cert = X509Certificate2.CreateFromPemFile(
                    settings.CertificatePemPath,
                    keyPath
                );

                LogPemCertificateLoaded(logger);
                return cert;
            }
            catch (Exception ex)
            {
                LogPemCertificateLoadFailed(logger, ex, settings.CertificatePemPath);
                // Continue to fallback
            }
        }
        else
        {
            LogCertificatePemPathNotConfigured(logger);
        }

        // 2. Fallback: .NET developer certificate (generated by `dotnet dev-certs`)
        try
        {
            var devCertPath = Path.Combine(
                Environment.GetFolderPath(Environment.SpecialFolder.UserProfile),
                ".dotnet",
                "devcert.pfx"
            );

            if (File.Exists(devCertPath))
            {
                LogUsingDevCertificate(logger, devCertPath);
                var devCert = X509CertificateLoader.LoadPkcs12FromFile(devCertPath, null);
                LogDevCertificateLoaded(logger);
                return devCert;
            }
            else
            {
                LogDevCertificateNotFound(logger, devCertPath);
            }
        }
        catch (Exception ex)
        {
            LogDevCertificateLoadFailed(logger, ex);
        }

        // 3. No certificate found
        LogNoCertificateFound(logger);
        return null;
    }

    /// <summary>
    /// Applies the HTTPS configurations to the HttpsConnectionAdapterOptions.
    /// </summary>
    public static void ConfigureHttpsOptions(
        HttpsConnectionAdapterOptions httpsOptions,
        IConfiguration configuration,
        ILogger logger,
        Action<HttpsConnectionAdapterOptions>? additionalConfig = null,
        bool throwIfNoCertificate = true)
    {
        var settings = LoadHttpsSettings(configuration, logger);
        var cert = LoadCertificate(settings, logger);

        if (cert != null)
        {
            httpsOptions.ServerCertificate = cert;
        }
        else
        {
            LogCannotLoadCertificate(logger);
            if (throwIfNoCertificate)
            {
                throw new InvalidOperationException(
                    "No valid HTTPS certificate found. " +
                    "Make sure to configure CertificatePemPath/CertificateKeyPath or run 'dotnet dev-certs https --trust'."
                );
            }
        }

        // TLS Protocols
        if (settings.SslProtocols.Length > 0)
        {
            var protocols = SslProtocols.None;
            foreach (var proto in settings.SslProtocols)
            {
                if (Enum.TryParse<SslProtocols>(proto, ignoreCase: true, out var p))
                    protocols |= p;
            }
            if (protocols != SslProtocols.None)
                httpsOptions.SslProtocols = protocols;
        }

        // Client Certificate Mode
        if (Enum.TryParse<ClientCertificateMode>(settings.ClientCertificateMode, ignoreCase: true, out var clientMode))
        {
            httpsOptions.ClientCertificateMode = clientMode;
        }

        // Additional configuration provided by the caller
        additionalConfig?.Invoke(httpsOptions);
    }

    #region Logs (source-generated)

    [LoggerMessage(Level = LogLevel.Information, Message = "HTTPS CertificatePemPath overridden by env var: {Path}")]
    private static partial void LogCertificatePemPathOverridden(ILogger logger, string path);

    [LoggerMessage(Level = LogLevel.Information, Message = "HTTPS CertificateKeyPath overridden by env var: {Path}")]
    private static partial void LogCertificateKeyPathOverridden(ILogger logger, string path);

    [LoggerMessage(Level = LogLevel.Information, Message = "HTTPS SslProtocols overridden by env var: {Protocols}")]
    private static partial void LogSslProtocolsOverridden(ILogger logger, string protocols);

    [LoggerMessage(Level = LogLevel.Information, Message = "HTTPS ClientCertificateMode overridden by env var: {Mode}")]
    private static partial void LogClientCertificateModeOverridden(ILogger logger, string mode);

    [LoggerMessage(Level = LogLevel.Debug, Message = "CertificateKeyPath not provided. Using fallback: {KeyPath}")]
    private static partial void LogCertificateKeyPathFallback(ILogger logger, string? keyPath);

    [LoggerMessage(Level = LogLevel.Information, Message = "Loading PEM certificate: {CertPath} (Key: {KeyPath})")]
    private static partial void LogLoadingPemCertificate(ILogger logger, string certPath, string? keyPath);

    [LoggerMessage(Level = LogLevel.Information, Message = "PEM certificate loaded successfully.")]
    private static partial void LogPemCertificateLoaded(ILogger logger);

    [LoggerMessage(Level = LogLevel.Error, Message = "Failed to load PEM certificate from {Path}")]
    private static partial void LogPemCertificateLoadFailed(ILogger logger, Exception ex, string path);

    [LoggerMessage(Level = LogLevel.Warning, Message = "CertificatePemPath not configured. Trying fallback to development certificate.")]
    private static partial void LogCertificatePemPathNotConfigured(ILogger logger);

    [LoggerMessage(Level = LogLevel.Warning, Message = "Using .NET development certificate: {Path}")]
    private static partial void LogUsingDevCertificate(ILogger logger, string path);

    [LoggerMessage(Level = LogLevel.Information, Message = "Development certificate loaded successfully.")]
    private static partial void LogDevCertificateLoaded(ILogger logger);

    [LoggerMessage(Level = LogLevel.Error, Message = "Development certificate not found at {Path}")]
    private static partial void LogDevCertificateNotFound(ILogger logger, string path);

    [LoggerMessage(Level = LogLevel.Error, Message = "Failed to load development certificate.")]
    private static partial void LogDevCertificateLoadFailed(ILogger logger, Exception ex);

    [LoggerMessage(Level = LogLevel.Critical, Message = "No valid certificate found. HTTPS will not work.")]
    private static partial void LogNoCertificateFound(ILogger logger);

    [LoggerMessage(Level = LogLevel.Error, Message = "Could not load a valid certificate.")]
    private static partial void LogCannotLoadCertificate(ILogger logger);
    #endregion
}